/** WHYLOG.md - the changelog's wiser sibling. */
import fs from 'node:fs';
import path from 'node:path';
import { isoDate } from './util.js';
import { topDecisions } from './search.js';
import { topRisk } from './risk.js';
import { lsFiles } from './git.js';

export function buildWhylog(ctx, opts) {
  const o = opts || {};
  const limit = o.limit || 40;
  const label = o.label || 'this repository';
  const alive = new Set(lsFiles(ctx.cwd));
  const rows = topDecisions(ctx.db, limit * 4).filter(function (r) { return r.rationale; }).slice(0, limit);
  const risk = topRisk(ctx.db, 60).filter(function (r) { return alive.has(r.path); }).slice(0, 8);
  const pickPaths = function (r) {
    const all = String(r.paths || '').split(/\s+/).filter(Boolean);
    const live = all.filter(function (p) { return alive.has(p); });
    return (live.length ? live : all).slice(0, 4);
  };
  const head = (ctx.head || '').slice(0, 8);
  const date = new Date().toISOString().slice(0, 10);
  const out = [];
  out.push('# WHYLOG');
  out.push('');
  out.push('> Git blame tells you *who*. This file tells you *why*.');
  out.push('>');
  out.push('> Every non-obvious decision this repository had to make, distilled from its own history.');
  out.push('> Generated by [whygit](https://github.com/whygit/whygit) - rebuilt from git, never hand-edited.');
  out.push('');
  out.push('`' + label + '` \u00b7 ' + ctx.stats.commits + ' commits indexed \u00b7 HEAD `' + head + '` \u00b7 ' + date);
  out.push('');
  out.push('## How to use this file');
  out.push('');
  out.push('- **Before changing code**, search this file for the file you are about to touch: `grep -n "src/your/file.py" WHYLOG.md`.');
  out.push('- **If a decision below contradicts what you were about to do**, trust the decision until you can explain why it no longer applies.');
  out.push('- **When you change something non-obvious**, write the reason in the commit body - whygit picks it up on the next rebuild.');
  out.push('- The same index is available to agents over MCP: `whygit mcp`.');
  out.push('');
  out.push('## Load-bearing decisions');
  out.push('');
  rows.forEach(function (r, i) {
    const paths = pickPaths(r);
    out.push('### ' + (i + 1) + '. ' + (r.title || '(untitled)'));
    out.push('');
    out.push('`' + isoDate(r.ts) + '` \u00b7 `' + String(r.sha).slice(0, 8) + '` \u00b7 ' + (r.author || 'unknown') + ' \u00b7 ' + (r.kind || 'change'));
    out.push('');
    if (r.rationale) out.push('> ' + String(r.rationale).replace(/\n+/g, ' '));
    if (paths.length) {
      out.push('');
      out.push('Touches: ' + paths.map(function (p) { return '`' + p + '`'; }).join(', '));
    }
    out.push('');
  });
  if (risk.length) {
    out.push('## The cursed files');
    out.push('');
    out.push('Most churn, most fixes, most authors. Read this list before refactoring - the history here is load-bearing.');
    out.push('');
    out.push('| File | Score | Commits | Fixes | Authors |');
    out.push('| --- | ---: | ---: | ---: | ---: |');
    for (const r of risk) {
      out.push('| `' + r.path + '` | ' + (Math.round(r.score * 10) / 10) + ' | ' + r.commits + ' | ' + r.fixes + ' | ' + r.authors + ' |');
    }
    out.push('');
  }
  out.push('## House rule');
  out.push('');
  out.push('```');
  out.push('WHY: <the reason, in one sentence>');
  out.push('```');
  out.push('');
  out.push('Put that line in any commit body that changes behaviour for a non-obvious reason. Nothing else to configure.');
  out.push('');
  return out.join('\n');
}

export function writeWhylog(ctx, opts) {
  const o = opts || {};
  const file = path.join(ctx.cwd, o.file || 'WHYLOG.md');
  const body = buildWhylog(ctx, o);
  fs.writeFileSync(file, body, 'utf8');
  return { file: file, bytes: Buffer.byteLength(body), decisions: (body.match(/^### /gm) || []).length };
}
