/** Turn raw commit text into a structured why-decision. */

const BOT_RE = /(\[bot\]|-bot@|^bot$|dependabot|renovate|github-actions|pre-commit-ci|greenkeeper|snyk-bot|imgbot|allcontributors|semantic-release|autofix)/i;

const NOISE_RE = [
  /^signed-off-by:/i,
  /^co-authored-by:/i,
  /^reviewed-by:/i,
  /^acked-by:/i,
  /^tested-by:/i,
  /^change-id:/i,
  /^bug:/i,
  /^see also:/i,
  /^refs?:\s*#?\d+/i,
  /^fix(?:e[sd])?:?\s*#\d+$/i,
  /^closes?:?\s*#\d+$/i,
  /^cc\s+@/i,
  /^generated by /i,
  /^this (?:pr|commit|change) was /i,
  /^\[skip ci\]/i,
  /^conflicts?:/i,
  /^-{3,}$/,
  /^={3,}$/,
];

const CAUSAL = [
  /\b(because|since|so that|in order to|to avoid|to prevent|otherwise|which caused|due to|the reason|this ensures|so we|so it|as a result|which means|that way|to make sure|to fix|workaround|root cause|regression|edge case|race condition|memory leak|deadlock|timeout|overflow|deprecated|backwards?[- ]compat)/i,
  /(因为|由于|所以|因此|导致|避免|防止|否则|为了|兼容|回滚|修复|临时方案|根因|边界情况|竞态|内存泄漏|死锁|超时|溢出|已废弃)/,
];

const FIX_RE = /\b(fix|fixes|fixed|revert|reverts|hotfix|regression|bug|broken|crash|oops|workaround|patch)\b|修复|回滚|修复|bug/i;

const BULK_RE = /^(bump|update deps|update dependencies|release|chore\(deps\)|version bump|v?\d+\.\d+\.\d+$)/i;

const COMMENT_RE = /^\s*(?:\/\/|#|\/\*|\*|--|;)\s*(?:NOTE|WHY|HACK|IMPORTANT|XXX|WARNING|TODO|FIXME)[:\s-]+(.{8,240})/i;

export function isBot(author, email) {
  return BOT_RE.test(String(author || '')) || BOT_RE.test(String(email || ''));
}

export function isTrivial(subject) {
  return BULK_RE.test(String(subject || '').trim());
}

export function stripNoise(body) {
  const lines = String(body || '').split(/\r?\n/);
  const kept = [];
  for (const line of lines) {
    const t = line.trim();
    if (!t) { kept.push(''); continue; }
    if (NOISE_RE.some(function (re) { return re.test(t); })) continue;
    if (/^https?:\/\/\S+$/.test(t)) continue;
    kept.push(t);
  }
  return kept.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

export function splitSentences(text) {
  const out = [];
  for (const para of String(text || '').split(/\n\s*\n|\n(?=\s*[-*\d]\s)/)) {
    const clean = para.replace(/\s+/g, ' ').trim();
    if (!clean) continue;
    const parts = clean.split(/(?<=[.!?;])\s+(?=[A-Z0-9])|(?<=[。！？；])/);
    for (const p of parts) {
      const s = p.trim();
      if (s) out.push(s);
    }
  }
  return out;
}

/** Remove the subject if the body repeats it (squash-merge artefact). */
export function dedupeSubject(body, subject) {
  const b = String(body || '').trim();
  const s = String(subject || '').trim();
  if (!b || !s) return b;
  const lines = b.split(/\r?\n/);
  const first = lines[0].trim();
  const norm = function (x) { return x.toLowerCase().replace(/[.:;,]+$/, '').trim(); };
  const a = norm(first);
  const t = norm(s);
  if (a === t || (t.length >= 12 && a.startsWith(t.slice(0, 40)))) {
    return lines.slice(1).join('\n').trim();
  }
  return b;
}

export function scoreSentence(sentence) {
  const s = String(sentence || '');
  if (s.length < 25 || s.length > 400) return 0;
  let score = 0;
  for (const re of CAUSAL) if (re.test(s)) { score += 3; break; }
  if (/\b(?:instead of|rather than|previously|used to|before this)\b/i.test(s)) score += 1.2;
  if (/`[^`]+`|\b[A-Z][A-Za-z0-9]+\.[A-Za-z0-9]+\b/.test(s)) score += 0.6;
  if (/^[-*]\s/.test(s)) score -= 0.5;
  if (/^(see|ref|link)\b/i.test(s)) score -= 2;
  return score;
}

export function extractRationale(subject, body) {
  const cleanBody = dedupeSubject(stripNoise(body), subject);
  const sentences = splitSentences(cleanBody).filter(function (s) { return s.length >= 20; });
  let best = null;
  let bestScore = 0;
  for (const s of sentences) {
    const sc = scoreSentence(s);
    if (sc > bestScore) { bestScore = sc; best = s; }
  }
  if (best && bestScore >= 1) {
    const r = trimSentence(best);
    if (sameText(r, subject)) return { rationale: '', confidence: 0.3, source: 'subject-only' };
    return { rationale: r, confidence: bestScore >= 3 ? 0.9 : 0.6, source: 'body' };
  }
  if (sentences.length) {
    const r = trimSentence(sentences[0]);
    if (sameText(r, subject)) return { rationale: '', confidence: 0.3, source: 'subject-only' };
    return { rationale: r, confidence: 0.4, source: 'body-weak' };
  }
  return { rationale: '', confidence: best ? 0.3 : 0.15, source: 'subject-only' };
}

function sameText(a, b) {
  const norm = function (x) { return String(x || '').toLowerCase().replace(/[^a-z0-9\u3400-\u9fff]+/g, ' ').trim(); };
  const x = norm(a);
  const y = norm(b);
  if (!x || !y) return false;
  return x === y || (y.length >= 16 && x.startsWith(y));
}

export function trimSentence(s) {
  let t = String(s).trim().replace(/^[-*\d.]+\s+/, '').replace(/\s+/g, ' ');
  if (t.length > 320) t = t.slice(0, 317).trimEnd() + '...';
  return t;
}

/** Mine intent-bearing comments from added lines of a diff. */
export function mineComments(files) {
  const found = [];
  for (const f of files || []) {
    for (const h of f.hunks || []) {
      for (const line of h.added || []) {
        const m = line.match(COMMENT_RE);
        if (m && m[1]) found.push({ path: f.path, text: trimSentence(m[1]) });
      }
    }
  }
  return found.slice(0, 5);
}

export function hasFixWord(text) {
  return FIX_RE.test(String(text || ''));
}

export function cleanSubject(subject) {
  return String(subject || '').replace(/\s+/g, ' ').trim();
}

export function classify(kind) {
  return kind || 'change';
}
